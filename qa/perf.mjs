import { chromium } from 'playwright'
const [w = 640, h = 400, sel = 'acto-1', frac = 0.05] = process.argv.slice(2)
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const p = await b.newPage({ viewport: { width: +w, height: +h } })
p.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && console.log('C', m.text().slice(0, 200)))
p.on('pageerror', (e) => console.log('ERR', e.message))
const t0 = Date.now()
await p.goto('http://localhost:4173/')
await p.evaluate(([id, f]) => { const el = document.getElementById(id); scrollTo(0, el.getBoundingClientRect().top + scrollY + f * (el.offsetHeight - innerHeight)) }, [sel, +frac])
await p.waitForFunction((id) => { const e = document.getElementById(id); return e.querySelector('canvas') && !e.querySelector('.exp-loading,.a1-scene-fallback') }, sel, { timeout: 300000 })
console.log('ready after', (Date.now() - t0) / 1000, 's')
const fps = await p.evaluate(() => new Promise((res) => { let n = 0; const s = performance.now(); const f = () => { n++; if (performance.now() - s < 4000) requestAnimationFrame(f); else res(n / 4) }; requestAnimationFrame(f) }))
console.log('fps', fps)
await p.screenshot({ path: `qa/perf-${sel}.png`, timeout: 300000 })
await b.close()
